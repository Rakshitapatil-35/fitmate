/**
 * Helper to fetch a brand by ID
 */
export function getBrandById(brandId) {
  return BRAND_DATABASE.find((b) => b.id === brandId) || null
}

/**
 * Helper to get available charts for a brand and audience
 */
export function getBrandChartsForAudience(brand, audience) {
  if (!brand || !brand.charts) return []
  return Object.entries(brand.charts)
    .filter(([key]) => key.startsWith(`${audience}:`))
    .map(([key, chart]) => ({
      key,
      category: key.split(':')[1],
      ...chart,
    }))
}

/**
 * Filter brands by search query, sector, and audience
 */
export function filterBrands({ query = '', sector = 'all', audience = 'all' }) {
  const cleanQ = query.trim().toLowerCase()
  return BRAND_DATABASE.filter((brand) => {
    // 1. Sector
    if (sector !== 'all' && brand.sector !== sector) return false
    // 2. Audience
    if (audience !== 'all' && brand.supportedAudiences && !brand.supportedAudiences.includes(audience)) {
      return false
    }
    // 3. Search text
    if (cleanQ) {
      const matchName = brand.name.toLowerCase().includes(cleanQ)
      const matchCountry = brand.country.toLowerCase().includes(cleanQ)
      const matchTier = (brand.tier || '').toLowerCase().includes(cleanQ)
      const matchNotes = (brand.notes || '').toLowerCase().includes(cleanQ)
      if (!matchName && !matchCountry && !matchTier && !matchNotes) return false
    }
    return true
  })
}
